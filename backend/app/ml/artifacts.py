def _metric_lines(results: dict) -> str:
    """Holdout metric bullets vs baseline; shared by supervised and forecasting READMEs."""
    return "\n".join(
        f"- {name}: {value} (baseline: {results['holdout']['baseline_metrics'].get(name, 'n/a')})"
        for name, value in results["holdout"]["metrics"].items()
    )


