def build_bundle(run_id: str, outcome: RunOutcome, plan: dict) -> str:
    """Write the bundle directory and zip it. Returns the zip path."""
    results = outcome.results
    task_family = outcome.meta["task_family"]
    bundle_dir = ARTIFACTS_DIR / run_id / "bundle"
    if bundle_dir.exists():
        shutil.rmtree(bundle_dir)
    bundle_dir.mkdir(parents=True)

    meta = {
        "feature_columns": outcome.meta["feature_columns"],
        "target_column": plan["target_column"],
        "task_type": plan["task_type"],
        "label_classes": outcome.meta["label_classes"],
        "methodology_id": plan["methodology_id"],
        "data_shape": outcome.meta["data_shape"],
        "task_family": task_family,
    }
    if task_family == "forecasting":
        meta.update(
            {
                "time_column": outcome.meta["time_column"],
                "horizon": outcome.meta["horizon"],
                "freq": outcome.meta["freq"],
                "framing": outcome.meta["framing"],
            }
        )

    joblib.dump({"pipeline": outcome.artifact, "meta": meta}, bundle_dir / "model.joblib")

    if task_family == "forecasting":
        train_py = _generate_train_py_forecasting(outcome, plan)
        serve_py = _generate_serve_py_forecasting(plan)
        readme = _generate_readme_forecasting(outcome, plan, results)
    else:
        train_py = _generate_train_py(outcome, plan)
        serve_py = _generate_serve_py(plan)
        readme = _generate_readme(outcome, plan, results)

    (bundle_dir / "train.py").write_text(train_py, encoding="utf-8")
    (bundle_dir / "serve.py").write_text(serve_py, encoding="utf-8")
    (bundle_dir / "README.md").write_text(readme, encoding="utf-8")

    reqs = ["scikit-learn>=1.6", "pandas>=2.2", "joblib>=1.4", "fastapi>=0.115", "uvicorn>=0.32"]
    # sklearn model classes need nothing extra; non-sklearn libraries pin their own line.
    extra_reqs = {"lightgbm": "lightgbm>=4.5", "xgboost": "xgboost>=3.3", "prophet": "prophet>=1.3"}
    top_module = outcome.meta["spec"]["model"]["class"].split(".")[0]
    if top_module in extra_reqs:
        reqs.insert(0, extra_reqs[top_module])
    (bundle_dir / "requirements.txt").write_text("\n".join(reqs) + "\n", encoding="utf-8")

    zip_base = str(ARTIFACTS_DIR / run_id / "model_bundle")
    zip_path = shutil.make_archive(zip_base, "zip", bundle_dir)
    return zip_path
