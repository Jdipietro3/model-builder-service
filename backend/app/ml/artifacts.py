def _build_lag_matrix(y, ts, lags, rolling, calendar):
    """Trailing lag / rolling-mean / calendar features (rolling means are shifted by one
    step so a row never sees its own target — no leakage)."""
    start = max([max(lags) if lags else 0] + [max(rolling) if rolling else 0])
    rows, targets = [], []
    for i in range(start, len(y)):
        feats = [y[i - l] for l in lags]
        feats += [float(np.mean(y[i - w:i])) for w in rolling]
        if calendar:
            t = ts[i]
            feats += [t.dayofweek, t.day, t.month]
        rows.append(feats)
        targets.append(y[i])
    return np.asarray(rows, float), np.asarray(targets, float)


def _recursive_forecast(model, hist_y, future_ts, lags, rolling, calendar):
    """Predict one step, append it, rebuild features, repeat. Error compounds."""
    work = list(hist_y)
    preds = []
    for t in future_ts:
        i = len(work)
        feats = [work[i - l] for l in lags]
        feats += [float(np.mean(work[i - w:i])) for w in rolling]
        if calendar:
            feats += [t.dayofweek, t.day, t.month]
        p = float(model.predict(np.asarray([feats], float))[0])
        preds.append(p)
        work.append(p)
    return np.asarray(preds, float)


